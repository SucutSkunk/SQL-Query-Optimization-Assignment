-- 1~5. 윈도우 함수로 상세 행 유지하며 고객별 총 구매금액 표시
select
	o.order_id,
	o.customer_id,
	oi.product_id,
	oi.qty,
	oi.price,
	oi.qty * oi.price as item_amount,
	sum(oi.qty * oi.price) over (
        partition by o.customer_id
    ) as customer_total_amount
from
	orders o
join order_items oi on
	o.order_id = oi.order_id
order by
	o.customer_id,
	o.order_id,
	oi.product_id;

