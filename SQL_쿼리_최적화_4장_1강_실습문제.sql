/*
============================================================
실습 마무리
============================================================
아래 내용을 한 문단으로 정리하세요.

Q1.
GROUP BY는 같은 그룹에 속한 여러 행을 하나의 결과 행으로 압축해서 보여주지만,
윈도우 함수는 원본 행 개수를 그대로 유지한 채 각 행 옆에 그룹 단위 계산 결과를 추가 컬럼처럼 붙여준다는 점이 가장 큰 차이다.

Q2.
PARTITION BY: 데이터를 어떤 그룹으로 나눠 계산할지 정한다
ORDER BY: 그 그룹 안에서 계산에 사용할 행의 순서를 정한다
프레임: 그 순서 중에서 현재 행을 기준으로 실제로 어디까지의 행을 계산에 포함할지를 정한다

Q3.
PARTITION BY와 ORDER BY로 지정한 계산 순서를 맞추기 위해
내부적으로 Sort가 수행될 수 있고, WindowAgg는 그렇게 정렬된 데이터를 이용해
실제 윈도우 함수 계산을 수행하는 노드다.
대용량 데이터에서는 이 Sort 비용이 전체 쿼리 성능에 큰 영향을 줄 수 있으므로,
실행계획에서 WindowAgg와 그 하위의 Sort 노드를 확인하여
파티션, 정렬 대상 컬럼에 인덱스가 필요한지 판단해야 한다.
